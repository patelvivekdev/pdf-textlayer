"""Write ``crates/pdf-textlayer/src/metrics_data.rs`` from PyMuPDF's fonts.

The Rust writer sizes each run with the same advance widths PyMuPDF used, so
its output lines up with files written by the 0.2 Python writer. Run this
only when the tables need regenerating:

    uv run python scripts/generate_metrics.py
"""

from __future__ import annotations

from pathlib import Path

import pymupdf

OUTPUT = (
    Path(__file__).resolve().parents[1] / "crates/pdf-textlayer/src/metrics_data.rs"
)
# Rust constant -> PyMuPDF font name. The first two size the overlay. The rest
# only place native text set in a standard font that states no widths.
FONTS = {
    "HELVETICA": "helv",
    "TIMES": "tiro",
    "HELVETICA_BOLD": "hebo",
    "TIMES_BOLD": "tibo",
    "TIMES_ITALIC": "tiit",
    "TIMES_BOLD_ITALIC": "tibi",
}


def advances(font_name: str) -> list[tuple[int, int]]:
    font = pymupdf.Font(font_name)
    table: list[tuple[int, int]] = []

    for codepoint in range(0x01, 0x10000):
        if 0xD800 <= codepoint <= 0xDFFF or not font.has_glyph(codepoint):
            continue

        advance = font.glyph_advance(codepoint) * 1000
        if advance <= 0:
            continue

        if abs(advance - round(advance)) > 1e-3:
            raise ValueError(f"{font_name} U+{codepoint:04X}: advance {advance}")

        table.append((codepoint, round(advance)))

    return table


def main() -> None:
    lines = [
        "// Generated by scripts/generate_metrics.py. Do not edit.",
        "//",
        "// (codepoint, advance in 1/1000 em), sorted by codepoint.",
        "",
    ]

    for constant, font_name in FONTS.items():
        table = advances(font_name)
        lines.append("#[rustfmt::skip]")
        lines.append(f"pub(crate) static {constant}: [(u16, u16); {len(table)}] = [")

        for start in range(0, len(table), 6):
            row = ", ".join(
                f"(0x{codepoint:04X}, {advance})"
                for codepoint, advance in table[start : start + 6]
            )
            lines.append(f"    {row},")

        lines.append("];")
        lines.append("")

    OUTPUT.write_text("\n".join(lines))
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
